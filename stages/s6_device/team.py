"""Writes Examples/PhotoSearchDemo/Team.xcconfig (gitignored) with the signing team from App Store Connect.

The App Store Connect API has no "team id" field; the team id is the OU of every signing certificate's subject.
So this lists the certificates with `asc` (already authenticated on the founder's Mac) and reads the OU with
`openssl`. Certificates are public; nothing secret is printed or written.

    uv run --exact --group convert python -m stages.s6_device.team
"""

from __future__ import annotations

import base64
import json
import re
import subprocess
from pathlib import Path

from egcm.paths import ROOT

TEAM_XCCONFIG = ROOT / "Examples" / "PhotoSearchDemo" / "Team.xcconfig"
_OU = re.compile(r"organizationalUnitName\s*=\s*([A-Z0-9]{10})\b")


def team_ids(certificates: dict, subject_of=None) -> set[str]:
    """Team ids (10 characters) from `asc certificates list --fields certificateContent --output json`."""
    subject_of = subject_of or _subject
    out = set()
    for c in certificates.get("data", []):
        content = c.get("attributes", {}).get("certificateContent")
        if content:
            out.update(_OU.findall(subject_of(base64.b64decode(content))))
    return out


def _subject(der: bytes) -> str:
    r = subprocess.run(["openssl", "x509", "-inform", "DER", "-noout", "-subject", "-nameopt", "multiline"],
                       input=der, capture_output=True, check=True)
    return r.stdout.decode()


def lookup_team_id() -> str:
    r = subprocess.run(["asc", "certificates", "list", "--fields", "certificateType,certificateContent",
                        "--paginate", "--output", "json"], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("`asc certificates list` failed; check `asc auth status --validate`")
    ids = team_ids(json.loads(r.stdout))
    if len(ids) != 1:
        raise RuntimeError(f"expected one team id across the signing certificates, found {len(ids)}; "
                           "write Examples/PhotoSearchDemo/Team.xcconfig by hand: DEVELOPMENT_TEAM = <id>")
    return ids.pop()


def render(team_id: str) -> str:
    return f"// Generated by stages/s6_device/team.py. Gitignored: the signing team of this Mac's developer.\n" \
           f"DEVELOPMENT_TEAM = {team_id}\n"


def ensure_team_xcconfig(path: Path = TEAM_XCCONFIG) -> Path:
    """Writes Team.xcconfig unless it already sets DEVELOPMENT_TEAM."""
    if path.is_file() and "DEVELOPMENT_TEAM" in path.read_text():
        return path
    path.write_text(render(lookup_team_id()))
    return path


if __name__ == "__main__":
    print(f"wrote {ensure_team_xcconfig()}")
