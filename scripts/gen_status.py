"""Write STATUS.md from artifacts/*/report.json (and the committed docs/results/*.json) and print it.

Run as `python -m scripts.gen_status`.
"""

from __future__ import annotations

import sys
from pathlib import Path

from egcm.paths import ROOT, STAGES
from egcm.provenance import is_stale
from egcm.report import Report, read_report


def load(root: Path) -> dict[str, Report | str]:
    """Stage name -> Report, or an error string if report.json is unreadable. Only stages that have a report."""
    out: dict[str, Report | str] = {}
    for stage in STAGES:
        p = root / "artifacts" / stage / "report.json"
        if p.is_file():
            try:
                out[stage] = read_report(p)
            except Exception as e:
                out[stage] = f"unreadable report.json: {type(e).__name__}"
    return out


def load_results(root: Path) -> dict[str, Report | str]:
    """docs/results/<name>.json (reports copied there to be committed, e.g. s6 per device) -> Report or error."""
    out: dict[str, Report | str] = {}
    for p in sorted((root / "docs" / "results").glob("*.json")):
        try:
            out[p.name] = read_report(p)
        except Exception as e:
            out[p.name] = f"unreadable: {type(e).__name__}"
    return out


def fmt(v: object) -> str:
    if isinstance(v, bool) or v is None:
        return str(v).lower()
    if isinstance(v, float):
        return f"{v:.6g}"
    return str(v)


def key_metrics(r: Report) -> str:
    """The gated metrics (or all metrics if the report has no gate values) as `name=value`, in gate order."""
    keys = list(r.gate_values) or list(r.metrics)
    return ", ".join(f"{k}={fmt(r.metrics.get(k))}" for k in keys) or "-"


def stale(r: Report, root: Path) -> bool:
    try:
        return is_stale(r, root)
    except Exception:
        return True  # can't tell (e.g. no git): treat as stale


def render(root: Path = ROOT) -> str:
    reports = load(root)
    lines = ["# Status", "", "Generated by `just status` from `artifacts/*/report.json`. Do not edit by hand.", ""]
    if not reports:
        lines.append("No stages run yet. Next: `just stage 0`.")
        return "\n".join(lines + results_section(root)) + "\n"
    lines += ["| stage | status | passed | stale | git sha | key metrics | failures |", "|---|---|---|---|---|---|---|"]
    nxt = None
    for stage in STAGES:
        r = reports.get(stage)
        if r is None:
            nxt = nxt or stage
            continue
        if isinstance(r, str):
            lines.append(f"| {stage} | invalid | no | - | - | - | {r} |")
            nxt = nxt or stage
            continue
        is_old = stale(r, root)
        sha = r.git_sha[:7] + ("+dirty" if r.git_dirty else "")
        lines.append(
            f"| {stage} | {r.status} | {'yes' if r.passed else 'no'} | {'yes' if is_old else 'no'} "
            f"| {sha or '-'} | {key_metrics(r)} | {'; '.join(r.failures) or '-'} |"
        )
        if not (r.status == "passed" and r.passed and not is_old):
            nxt = nxt or stage
    lines.append("")
    lines.append(f"Next: `just stage {nxt.split('_')[0][1:]}` ({nxt})." if nxt else "All stages pass and are current.")
    lines += results_section(root)
    return "\n".join(lines) + "\n"


def results_section(root: Path) -> list[str]:
    """Committed reports in docs/results/ (not checked for staleness: their upstream artifacts may not be here)."""
    results = load_results(root)
    if not results:
        return []
    lines = ["", "## Committed results (docs/results/)", "",
             "| file | stage | status | passed | git sha | key metrics |", "|---|---|---|---|---|---|"]
    for name, r in results.items():
        if isinstance(r, str):
            lines.append(f"| {name} | - | invalid | no | - | {r} |")
            continue
        lines.append(f"| {name} | {r.stage} | {r.status} | {'yes' if r.passed else 'no'} | {r.git_sha[:7] or '-'} "
                     f"| {key_metrics(r)} |")
    return lines


def main() -> None:
    text = render()
    (ROOT / "STATUS.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
