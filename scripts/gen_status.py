"""Write STATUS.md from artifacts/*/report.json and print it. Run as `python -m scripts.gen_status`."""

from __future__ import annotations

import sys
from pathlib import Path

from egcm.paths import ROOT, STAGES
from egcm.provenance import is_stale
from egcm.report import Report, read_report


def load(root: Path) -> dict[str, Report | str]:
    """Stage name -> Report, or an error string if report.json is unreadable. Only stages that have a report."""
    out: dict[str, Report | str] = {}
    for stage in STAGES:
        p = root / "artifacts" / stage / "report.json"
        if p.is_file():
            try:
                out[stage] = read_report(p)
            except Exception as e:
                out[stage] = f"unreadable report.json: {type(e).__name__}"
    return out


def stale(r: Report, root: Path) -> bool:
    try:
        return is_stale(r, root)
    except Exception:
        return True  # can't tell (e.g. no git): treat as stale


def render(root: Path = ROOT) -> str:
    reports = load(root)
    lines = ["# Status", "", "Generated by `just status` from `artifacts/*/report.json`. Do not edit by hand.", ""]
    if not reports:
        lines.append("No stages run yet. Next: `just stage 0`.")
        return "\n".join(lines) + "\n"
    lines += ["| stage | status | passed | stale | git sha | failures |", "|---|---|---|---|---|---|"]
    nxt = None
    for stage in STAGES:
        r = reports.get(stage)
        if r is None:
            nxt = nxt or stage
            continue
        if isinstance(r, str):
            lines.append(f"| {stage} | invalid | no | - | - | {r} |")
            nxt = nxt or stage
            continue
        is_old = stale(r, root)
        sha = r.git_sha[:7] + ("+dirty" if r.git_dirty else "")
        lines.append(
            f"| {stage} | {r.status} | {'yes' if r.passed else 'no'} | {'yes' if is_old else 'no'} "
            f"| {sha or '-'} | {'; '.join(r.failures) or '-'} |"
        )
        if not (r.status == "passed" and r.passed and not is_old):
            nxt = nxt or stage
    lines.append("")
    lines.append(f"Next: `just stage {nxt.split('_')[0][1:]}` ({nxt})." if nxt else "All stages pass and are current.")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render()
    (ROOT / "STATUS.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
